public class ImgflipMeme {
    public final String id;
    public final String name;
    public final String url;
    public final int width;
    public final int height;

    public ImgflipMeme(String id, String name, String url, int width, int height) {
        this.id = id;
        this.name = name;
        this.url = url;
        this.width = width;
        this.height = height;
    }
}
